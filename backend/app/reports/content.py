def build_subject_teacher_content(
    *, school_name: str, view: TeacherView, generated_at: datetime
) -> ReportContent:
    """Coaching report for one teacher's class-subject assignments (no teacher ranking)."""
    combined = view.combined
    support_total = sum(len(a.students_needing_support) for a in view.assignments)
    figures = [
        KeyFigure("Class-subject groups", str(len(view.assignments))),
        KeyFigure(
            "Papers",
            str(combined.student_count if combined else 0),
            f"{combined.appeared_count if combined else 0} with marks",
        ),
        KeyFigure(
            "Met the pass mark",
            pct1(combined.pass_percentage if combined else None),
            f"{combined.pass_count if combined else 0} papers",
        ),
        KeyFigure("Mean score", pct1(combined.mean_percentage if combined else None)),
        KeyFigure("Results needing follow-up", str(support_total)),
    ]

    rows: list[list[CellValue]] = []
    for a in view.assignments:
        s = a.stats
        rows.append(
            [
                a.class_label,
                a.subject_name,
                "Yes" if a.is_class_teacher else "No",
                s.student_count if s else None,
                s.appeared_count if s else None,
                s.pass_count if s else None,
                s.pass_percentage if s else None,
                s.mean_percentage if s else None,
                a.mean_change_points,
                len(a.students_needing_support) if a.in_exam else None,
                "Yes" if a.in_exam else "Not in this exam",
            ]
        )
    chart_pairs = [
        (f"{a.class_label} {a.subject_name}", float(a.stats.pass_percentage))
        for a in view.assignments
        if a.stats is not None and a.stats.pass_percentage is not None
    ]
    classes = Section(
        title="Your classes",
        sheet=SHEET_CLASSES,
        paragraphs=[
            "This view is for planning support. It summarises your classes' results and is "
            "not a rating or ranking of teaching."
        ],
        tables=[
            Table(
                title="Results by class and subject",
                columns=[
                    Column("Class", weight=0.8),
                    Column("Subject", weight=1.3),
                    Column("Class teacher", weight=0.9),
                    Column("Students", "int"),
                    Column("With marks", "int"),
                    Column("Passed", "int"),
                    Column("Pass %", "percent"),
                    Column("Mean %", "percent"),
                    Column("Change (pts)", "delta"),
                    Column("Need support", "int"),
                    Column("In exam", weight=1.1),
                ],
                rows=rows,
                empty_message="No teaching assignments in this exam's academic year.",
                note="Change = average per-student change in the subject % vs the previous exam.",
            )
        ],
        chart=(
            BarChart(
                title="Pass % by class and subject",
                labels=[p[0] for p in chart_pairs],
                values=[p[1] for p in chart_pairs],
            )
            if chart_pairs
            else None
        ),
    )
    coaching = Section(
        title="Coaching notes",
        bullets=[note for a in view.assignments for note in a.notes],
    )
    if not coaching.bullets:
        coaching.paragraphs.append("No notes for this exam.")

    support_rows: list[list[CellValue]] = []
    for a in view.assignments:
        for st in a.students_needing_support:
            status = "Absent" if st.is_absent else "Missing" if st.is_missing else "Below pass"
            support_rows.append(
                [a.class_label, a.subject_name, st.pseudo_id, st.full_name, st.marks, status]
            )
    support = Section(
        title="Students needing support",
        sheet=SHEET_STUDENTS,
        paragraphs=[
            "Students below the pass mark (or absent) in your subject. Small-group revision "
            "and a quick re-check usually help most."
        ],
        tables=[
            Table(
                title="Students below the pass mark, by class",
                columns=[
                    Column("Class", weight=0.7),
                    Column("Subject", weight=1.2),
                    Column("Pseudo ID"),
                    Column("Name", weight=2.0),
                    Column("Marks", "number"),
                    Column("Status", "status"),
                ],
                rows=support_rows,
                empty_message="Every student met the pass mark - well done.",
            )
        ],
    )
    narrative = list(view.notes) or ["No results to summarise for this exam yet."]
    return ReportContent(
        kind="subject_teacher",
        title=f"Subject teacher report - {view.teacher_name}",
        school_name=school_name,
        exam_name=view.exam.name,
        scope_label=f"Teacher {view.teacher_name}",
        generated_at=generated_at,
        figures=figures,
        narrative=narrative,
        sections=[classes, coaching, support, method_section()],
        sheets=[SHEET_SUMMARY, SHEET_CLASSES, SHEET_STUDENTS, SHEET_METHOD],
    )
