def method_section() -> Section:
    """'Calculation method' - the deterministic rules from ``app.analytics.calculations``."""
    bands = ", ".join(label for label, _, _ in DISTRIBUTION_BANDS)
    return Section(
        title="Calculation method",
        sheet=SHEET_METHOD,
        paragraphs=[
            "Every number in this report is computed by deterministic code from the recorded "
            "marks. No AI model calculates or changes any figure.",
        ],
        bullets=[
            "Only subjects configured for the exam count. Absent or missing papers count as "
            "failed and contribute 0 marks.",
            "A subject is passed when marks >= the pass mark. Subject % = marks / max marks x 100.",
            "Student % = total marks / total maximum marks x 100, rounded to 2 decimals "
            "(half-up). A student passes overall only when every configured subject is passed.",
            "Rank in section uses competition ranking (1, 2, 2, 4) by percentage.",
            "Pass rate counts every student (absent = fail). Mean, median, highest, lowest and "
            f"the distribution bands ({bands}) use only students who appeared.",
            "Change vs previous exam = current % - previous % (percentage points), for "
            "students present in both exams.",
            "At-risk rule - any of: failed at least one subject; dropped "
            f"{AT_RISK_DROP_POINTS} or more points vs the previous exam; overall below "
            f"{LOW_OVERALL_THRESHOLD}%. Severity is high with two or more reasons or "
            f"{HIGH_SEVERITY_FAILED_SUBJECTS}+ failed subjects, otherwise medium.",
            "Intervention plans are drafted by the AI agent (or a template when AI is off) and "
            "stay 'draft' until a teacher or administrator approves them.",
        ],
    )


def _class_table(summaries: Sequence[ClassSummary], at_risk: Sequence[AtRiskStudent]) -> Table:
    risk_by_class = Counter(a.class_section_id for a in at_risk)
    return Table(
        title="Class summary",
        columns=[
            Column("Class", weight=1.2),
            Column("Students", "int"),
            Column("Appeared", "int"),
            Column("Passed", "int"),
            Column("Failed", "int"),
            Column("Pass %", "percent"),
            Column("Mean %", "percent"),
            Column("Median %", "percent"),
            Column("Highest %", "percent"),
            Column("Lowest %", "percent"),
            Column("At risk", "int"),
        ],
        rows=[
            [
                s.class_label,
                s.student_count,
                s.appeared_count,
                s.pass_count,
                s.fail_count,
                s.pass_percentage,
                s.mean_percentage,
                s.median_percentage,
                s.highest_percentage,
                s.lowest_percentage,
                risk_by_class.get(s.class_section_id or -1, 0),
            ]
            for s in summaries
        ],
    )


def _distribution_table(summaries: Sequence[ClassSummary]) -> Table:
    return Table(
        title="Score distribution (students who appeared)",
        columns=[Column("Class", weight=1.2)]
        + [Column(f"{label}%", "int") for label, _, _ in DISTRIBUTION_BANDS],
        rows=[[s.class_label] + [b.count for b in s.distribution] for s in summaries],
    )


def _subject_tables(overview: ExamOverview, with_weakest: bool) -> tuple[Table, Table | None]:
    labels = {c.class_section_id: c.class_label for c in overview.class_summaries}
    columns = [
        Column("Subject", weight=1.6),
        Column("Max", "number"),
        Column("Pass mark", "number"),
        Column("Students", "int"),
        Column("Absent", "int"),
        Column("Below pass", "int"),
        Column("Pass %", "percent"),
        Column("Mean %", "percent"),
        Column("Change (pts)", "delta"),
    ]
    if with_weakest:
        columns.append(Column("Weakest section(s)", weight=1.8))
    rows: list[list[CellValue]] = []
    for s in overview.subject_summaries:
        o = s.overall
        below = o.student_count - o.pass_count - o.absent_count - o.missing_count
        row: list[CellValue] = [
            s.subject_name,
            s.max_marks,
            s.pass_marks,
            o.student_count,
            o.absent_count,
            below,
            o.pass_percentage,
            o.mean_percentage,
            s.mean_percentage_change,
        ]
        if with_weakest:
            weakest = []
            for sec in s.sections:
                if sec.class_section_id in s.weakest_sections and len(s.sections) > 1:
                    weakest.append(f"{sec.class_label} ({pct1(sec.stats.pass_percentage)})")
            row.append(", ".join(weakest) if weakest else "-")
        rows.append(row)
    main = Table(
        title="Subject summary",
        columns=columns,
        rows=rows,
        note="Change = change in the subject's mean % vs the previous exam (percentage points).",
    )
    matrix: Table | None = None
    if with_weakest and len(overview.class_summaries) > 1:
        section_ids = [
            c.class_section_id for c in overview.class_summaries if c.class_section_id is not None
        ]
        matrix_rows: list[list[CellValue]] = []
        flagged: set[tuple[int, int]] = set()
        for r_idx, s in enumerate(overview.subject_summaries):
            by_section = {sec.class_section_id: sec.stats.pass_percentage for sec in s.sections}
            matrix_row: list[CellValue] = [s.subject_name]
            for c_idx, sid in enumerate(section_ids, start=1):
                matrix_row.append(by_section.get(sid))
                if sid in s.weakest_sections:
                    flagged.add((r_idx, c_idx))
            matrix_rows.append(matrix_row)
        matrix = Table(
            title="Pass % by subject and section",
            columns=[Column("Subject", weight=1.6)]
            + [Column(labels.get(sid, "?"), "percent") for sid in section_ids],
            rows=matrix_rows,
            flagged=flagged,
            note="Highlighted cells mark the weakest section for each subject.",
        )
    return main, matrix


def _subject_chart(overview: ExamOverview, title: str) -> BarChart | None:
    pairs = [
        (s.subject_name, float(s.overall.pass_percentage))
        for s in overview.subject_summaries
        if s.overall.pass_percentage is not None
    ]
    if not pairs:
        return None
    return BarChart(title=title, labels=[p[0] for p in pairs], values=[p[1] for p in pairs])


def _student_table(overview: ExamOverview, title: str, include_class: bool, in_pdf: bool) -> Table:
    subjects = overview.subjects
    columns: list[Column] = []
    if include_class:
        columns.append(Column("Class"))
    columns += [
        Column("Rank", "int", 0.7),
        Column("Pseudo ID", weight=1.1),
        Column("Name", weight=2.2),
    ]
    columns += [Column(cfg.name, "number", 1.15) for cfg in subjects]
    columns += [
        Column("Total", "number"),
        Column("%", "percent"),
        Column("Result", "status"),
        Column("Change", "delta"),
    ]
    first_subject_col = len(columns) - len(subjects) - 4
    rows: list[list[CellValue]] = []
    flagged: set[tuple[int, int]] = set()
    for r_idx, r in enumerate(overview.results):
        change = overview.change_for(r.student_id)
        row: list[CellValue] = [r.class_label] if include_class else []
        row += [r.rank_in_section, r.pseudo_id, r.full_name]
        for c_off, cfg in enumerate(subjects):
            entry = r.subject(cfg.subject_id)
            row.append(_subject_cell(entry))
            if entry is not None and not entry.passed:
                flagged.add((r_idx, first_subject_col + c_off))
        row += [r.total, r.percentage, _result_status(r), change.delta if change else None]
        rows.append(row)
    return Table(
        title=title,
        columns=columns,
        rows=rows,
        flagged=flagged,
        in_pdf=in_pdf,
        note="AB = absent, - = no mark recorded. Highlighted marks are below the pass mark. "
        "Change = percentage points vs the previous exam.",
        empty_message="No students have results for this exam.",
    )


def _plans_by_student(plans: Sequence[PlanRow]) -> dict[int, list[PlanRow]]:
    grouped: dict[int, list[PlanRow]] = {}
    for p in plans:
        grouped.setdefault(p.student_id, []).append(p)
    return grouped


def _plan_summary(plans: Sequence[PlanRow]) -> str:
    if not plans:
        return "No plan yet"
    counts = Counter(p.status for p in plans)
    parts = [f"{counts[s]} {s.replace('_', ' ')}" for s in PLAN_STATUSES if counts.get(s)]
    return ", ".join(parts)


def _at_risk_section(
    at_risk: Sequence[AtRiskStudent],
    plans: Sequence[PlanRow],
    *,
    include_class: bool,
    include_counts: bool,
) -> Section:
    section = Section(title="Students needing support (at risk)", sheet=SHEET_AT_RISK)
    if not at_risk:
        section.paragraphs.append("No student meets the at-risk rule for this exam.")
        return section
    if include_counts:
        severity = Counter(a.severity for a in at_risk)
        section.tables.append(
            Table(
                title="At-risk students by severity",
                columns=[Column("Severity", "status"), Column("Students", "int")],
                rows=[["High", severity.get("high", 0)], ["Medium", severity.get("medium", 0)]],
            )
        )
        reasons: Counter[str] = Counter(reason.code for a in at_risk for reason in a.reasons)
        section.tables.append(
            Table(
                title="At-risk students by reason (a student can have several)",
                columns=[Column("Reason", weight=2), Column("Students", "int")],
                rows=[[REASON_LABELS[code], reasons.get(code, 0)] for code in REASON_LABELS],
            )
        )
    plans_by_student = _plans_by_student(plans)
    columns = [Column("Pseudo ID", weight=1.0), Column("Name", weight=1.8)]
    if include_class:
        columns.append(Column("Class", weight=0.8))
    columns += [
        Column("%", "percent", 0.8),
        Column("Change", "delta", 0.8),
        Column("Severity", "status", 0.9),
        Column("Reasons", weight=3.2),
        Column("Plans", weight=1.4),
    ]
    rows: list[list[CellValue]] = []
    for a in at_risk:
        row: list[CellValue] = [a.pseudo_id, a.full_name]
        if include_class:
            row.append(a.class_label)
        row += [
            a.percentage,
            a.delta,
            a.severity.capitalize(),
            "; ".join(r.detail for r in a.reasons),
            _plan_summary(plans_by_student.get(a.student_id, [])),
        ]
        rows.append(row)
    section.tables.append(Table(title="At-risk student list", columns=columns, rows=rows))
    return section


def _interventions_section(plans: Sequence[PlanRow], include_class: bool) -> Section:
    section = Section(title="Intervention plans", sheet=SHEET_INTERVENTIONS)
    counts = Counter(p.status for p in plans)
    status_rows: list[list[CellValue]] = [
        [PLAN_STATUS_LABELS[s], counts.get(s, 0)] for s in PLAN_STATUSES
    ]
    status_rows.append(["Total", len(plans)])
    section.tables.append(
        Table(
            title="Plan status",
            columns=[Column("Status", weight=2), Column("Plans", "int")],
            rows=status_rows,
        )
    )
    if not plans:
        section.paragraphs.append(
            "No intervention plans are linked to this exam yet. Start an agent run to draft "
            "plans for at-risk students."
        )
        return section
    columns = [Column("Pseudo ID"), Column("Name", weight=1.6)]
    if include_class:
        columns.append(Column("Class", weight=0.7))
    columns += [
        Column("Subject", weight=1.1),
        Column("Status", weight=1.1),
        Column("Reassess on", weight=1.0),
        Column("Plan (excerpt)", weight=4.0),
    ]
    rows: list[list[CellValue]] = []
    for p in sorted(plans, key=lambda p: (p.class_label, p.pseudo_id, p.plan_id)):
        row: list[CellValue] = [p.pseudo_id, p.full_name]
        if include_class:
            row.append(p.class_label)
        row += [
            p.subject_name or "General",
            PLAN_STATUS_LABELS.get(p.status, p.status),
            p.reassess_on.isoformat() if p.reassess_on else "-",
            _excerpt(p.plan_text),
        ]
        rows.append(row)
    section.tables.append(
        Table(
            title="Plans",
            columns=columns,
            rows=rows,
            note="Draft plans were written by the AI agent and are not in effect until a "
            "teacher approves them.",
        )
    )
    return section


def _comparison_section(
    overview: ExamOverview, previous: ExamOverview | None, scope: str
) -> Section:
    section = Section(title="Comparison with the previous exam")
    if overview.previous_exam is None or previous is None:
        section.paragraphs.append("There is no earlier exam to compare with.")
        return section
    curr, prev = overview.school_summary, previous.school_summary
    metrics: list[tuple[str, Decimal | int | None, Decimal | int | None, str]] = [
        ("Students", prev.student_count, curr.student_count, "int"),
        ("Pass %", prev.pass_percentage, curr.pass_percentage, "percent"),
        ("Mean %", prev.mean_percentage, curr.mean_percentage, "percent"),
        ("Median %", prev.median_percentage, curr.median_percentage, "percent"),
        ("At-risk students", len(previous.at_risk), len(overview.at_risk), "int"),
    ]
    rows: list[list[CellValue]] = []
    for label, p, c, _ in metrics:
        change: Decimal | int | None
        if isinstance(p, int) and isinstance(c, int):
            change = c - p
        else:
            change = _diff(
                c if isinstance(c, Decimal) else None, p if isinstance(p, Decimal) else None
            )
        rows.append([label, p, c, change])
    section.tables.append(
        Table(
            title=f"{scope}: {overview.previous_exam.name} vs {overview.exam.name}",
            columns=[
                Column("Measure", weight=1.6),
                Column(overview.previous_exam.name, "decimal"),
                Column(overview.exam.name, "decimal"),
                Column("Change", "delta"),
            ],
            rows=rows,
            note="Percentages are in %; change is in percentage points (or a count).",
        )
    )
    section.bullets.extend(_movement_sentences(overview))
    return section


def _movement_sentences(overview: ExamOverview) -> list[str]:
    changes = overview.changes
    if not changes or overview.previous_exam is None:
        return []
    mean_delta = _mean([c.delta for c in changes])
    improved = sum(1 for c in changes if c.delta >= 10)
    dropped = sum(1 for c in changes if c.delta <= -AT_RISK_DROP_POINTS)
    direction = "up" if mean_delta and mean_delta > 0 else "down"
    sentences = []
    if mean_delta is not None and mean_delta != 0:
        sentences.append(
            f"Across {_plural(len(changes), 'student')} who sat both exams, the average score "
            f"moved {direction} {pts1(mean_delta)} points since {overview.previous_exam.name}."
        )
    elif mean_delta is not None:
        sentences.append(
            f"Across {_plural(len(changes), 'student')} who sat both exams, the average score "
            f"is unchanged since {overview.previous_exam.name}."
        )
    sentences.append(
        f"{_plural(improved, 'student')} improved by 10 or more points; "
        f"{_plural(dropped, 'student')} dropped by {AT_RISK_DROP_POINTS} or more points."
    )
    return sentences


