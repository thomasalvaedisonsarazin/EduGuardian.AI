def _overview_narrative(
    overview: ExamOverview,
    previous: ExamOverview | None,
    plans: Sequence[PlanRow],
    *,
    compare_classes: bool,
) -> list[str]:
    summary = overview.school_summary
    if summary.student_count == 0:
        return [f"No marks have been recorded for {overview.exam.name} yet."]
    out = [
        f"{_plural(summary.student_count, 'student')} are in scope for {overview.exam.name}; "
        f"{summary.pass_count} passed every subject (pass rate {pct1(summary.pass_percentage)}"
        f", mean score {pct1(summary.mean_percentage)})."
    ]
    if previous is not None and overview.previous_exam is not None:
        change = _diff(summary.pass_percentage, previous.school_summary.pass_percentage)
        if change is not None and change != 0:
            verb = "rose" if change > 0 else "fell"
            out.append(
                f"The pass rate {verb} by {pts1(change)} points since "
                f"{overview.previous_exam.name} ({pct1(previous.school_summary.pass_percentage)}"
                f" -> {pct1(summary.pass_percentage)})."
            )
        elif change is not None:
            out.append(f"The pass rate is unchanged since {overview.previous_exam.name}.")

    rated: list[tuple[Decimal, str, int]] = [
        (s.overall.pass_percentage, s.subject_name, s.subject_id)
        for s in overview.subject_summaries
        if s.overall.pass_percentage is not None
    ]
    if len(rated) >= 2:
        average = quantize(sum((r[0] for r in rated), Decimal(0)) / len(rated))
        low_pct, low_name, low_id = min(rated)
        high_pct, high_name, high_id = max(rated, key=lambda r: (r[0], r[1]))
        gap = quantize(average - low_pct)
        if gap > 0:
            out.append(
                f"{low_name} has the lowest pass rate ({pct1(low_pct)}), {pts1(gap)} points "
                f"below the average subject pass rate ({pct1(average)})."
            )
        else:
            out.append(f"All subjects have the same pass rate ({pct1(average)}).")
        if high_id != low_id and high_pct != low_pct:
            out.append(f"{high_name} has the highest pass rate ({pct1(high_pct)}).")
        falling = [
            s
            for s in overview.subject_summaries
            if s.mean_percentage_change is not None and s.mean_percentage_change <= -5
        ]
        if falling:
            worst = min(falling, key=lambda s: s.mean_percentage_change or Decimal(0))
            out.append(
                f"{worst.subject_name}'s mean score fell by "
                f"{pts1(worst.mean_percentage_change or Decimal(0))} points vs the previous exam."
            )

    if compare_classes and len(overview.class_summaries) >= 2:
        classes = [c for c in overview.class_summaries if c.pass_percentage is not None]
        if classes:
            low = min(classes, key=lambda c: (c.pass_percentage, c.class_label))
            high = max(classes, key=lambda c: (c.pass_percentage or 0, c.class_label))
            if low.pass_percentage != high.pass_percentage:
                out.append(
                    f"Class pass rates range from {pct1(low.pass_percentage)} ({low.class_label})"
                    f" to {pct1(high.pass_percentage)} ({high.class_label})."
                )

    if overview.at_risk:
        high_count = sum(1 for a in overview.at_risk if a.severity == "high")
        reasons = Counter(r.code for a in overview.at_risk for r in a.reasons)
        code, count = sorted(reasons.items(), key=lambda kv: (-kv[1], kv[0]))[0]
        out.append(
            f"{_plural(len(overview.at_risk), 'student')} meet the at-risk rule "
            f"({high_count} high severity); the most common reason is "
            f"'{REASON_LABELS[code].lower()}' ({count})."
        )
    else:
        out.append("No student meets the at-risk rule.")

    if plans:
        counts = Counter(p.status for p in plans)
        out.append(
            f"{_plural(len(plans), 'intervention plan')} are linked to this exam: "
            f"{counts.get('approved', 0) + counts.get('in_progress', 0)} approved or in "
            f"progress, {counts.get('draft', 0)} awaiting teacher approval."
        )
    return out


def _summary_figures(summary: ClassSummary, at_risk: Sequence[AtRiskStudent]) -> list[KeyFigure]:
    high = sum(1 for a in at_risk if a.severity == "high")
    return [
        KeyFigure("Students", str(summary.student_count), f"{summary.appeared_count} appeared"),
        KeyFigure("Pass rate", pct1(summary.pass_percentage), f"{summary.pass_count} passed"),
        KeyFigure("Mean score", pct1(summary.mean_percentage)),
        KeyFigure("Median score", pct1(summary.median_percentage)),
        KeyFigure(
            "Highest / lowest",
            f"{pct1(summary.highest_percentage)} / {pct1(summary.lowest_percentage)}",
        ),
        KeyFigure("At risk", str(len(at_risk)), f"{high} high severity"),
    ]


