def build_principal_content(
    *,
    school_name: str,
    overview: ExamOverview,
    previous: ExamOverview | None,
    plans: Sequence[PlanRow],
    generated_at: datetime,
) -> ReportContent:
    """School-wide report for the principal."""
    classes = Section(title="Classes", sheet=SHEET_CLASSES)
    classes.tables.append(_class_table(overview.class_summaries, overview.at_risk))
    classes.tables.append(_distribution_table(overview.class_summaries))

    subject_table, matrix = _subject_tables(overview, with_weakest=True)
    subjects = Section(
        title="Subjects",
        sheet=SHEET_SUBJECTS,
        tables=[subject_table] + ([matrix] if matrix else []),
        chart=_subject_chart(overview, "Pass % by subject"),
    )
    students = Section(
        title="All student results",
        sheet=SHEET_STUDENTS,
        in_pdf=False,
        tables=[_student_table(overview, "Student results", include_class=True, in_pdf=False)],
    )
    plans_section = _interventions_section(plans, include_class=True)
    return ReportContent(
        kind="principal",
        title="Principal report",
        school_name=school_name,
        exam_name=overview.exam.name,
        scope_label="Whole school",
        generated_at=generated_at,
        figures=_summary_figures(overview.school_summary, overview.at_risk),
        narrative=_overview_narrative(overview, previous, plans, compare_classes=True),
        sections=[
            _comparison_section(overview, previous, "School"),
            classes,
            subjects,
            _at_risk_section(overview.at_risk, plans, include_class=True, include_counts=True),
            plans_section,
            students,
            method_section(),
        ],
        sheets=[
            SHEET_SUMMARY,
            SHEET_CLASSES,
            SHEET_SUBJECTS,
            SHEET_STUDENTS,
            SHEET_AT_RISK,
            SHEET_INTERVENTIONS,
            SHEET_METHOD,
        ],
    )


