"""Format-neutral report model + pure builders (no database access).

The builders turn deterministic analytics results (``ExamOverview`` / ``TeacherView``) and the
intervention plans linked to an exam into a :class:`ReportContent` - title, key figures,
narrative sentences, sections with typed tables and an optional bar chart. ``pdf.py`` and
``xlsx.py`` render the same model, so both formats always show identical numbers.

Narrative sentences are generated from the numbers only (no LLM), e.g.
"Maths has the lowest pass rate (62.5%), 14.2 points below the average subject pass rate".
"""

