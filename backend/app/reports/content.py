@dataclass(frozen=True)
class Column:
    header: str
    kind: ColumnKind = "text"
    weight: float = 1.0  # relative width (PDF); XLSX sizes columns from content


@dataclass
class Table:
    title: str
    columns: list[Column]
    rows: list[list[CellValue]]
    empty_message: str = "No data for this exam."
    note: str | None = None
    in_pdf: bool = True
    #: (row index, column index) cells to highlight as below the pass mark.
    flagged: set[tuple[int, int]] = field(default_factory=set)


@dataclass(frozen=True)
class KeyFigure:
    label: str
    value: str
    hint: str | None = None


@dataclass(frozen=True)
class BarChart:
    title: str
    labels: list[str]
    values: list[float]  # 0-100 percentages
    value_label: str = "Pass %"


@dataclass
class Section:
    title: str
    sheet: str = SHEET_SUMMARY
    paragraphs: list[str] = field(default_factory=list)
    bullets: list[str] = field(default_factory=list)
    tables: list[Table] = field(default_factory=list)
    chart: BarChart | None = None
    in_pdf: bool = True


@dataclass
class ReportContent:
    kind: str
    title: str
    school_name: str
    exam_name: str
    scope_label: str
    generated_at: datetime
    figures: list[KeyFigure]
    narrative: list[str]
    sections: list[Section]
    sheets: list[str]
    footer: str = FOOTER_TEXT

    @property
    def subtitle(self) -> str:
        return f"{self.exam_name} · {self.scope_label}"


@dataclass(frozen=True)
class PlanRow:
    """An intervention plan linked to the exam, already joined with student/subject names."""

    plan_id: int
    student_id: int
    pseudo_id: str
    full_name: str
    class_label: str
    subject_name: str | None
    status: str
    plan_text: str
    reassess_on: date | None
    run_id: int | None


# ---------------------------------------------------------------------------
# Formatting helpers (narrative only - tables keep raw typed values)
# ---------------------------------------------------------------------------


def pct1(value: Decimal | None) -> str:
    """``Decimal("62.50")`` -> ``"62.5%"``; None -> ``"n/a"``."""
    if value is None:
        return "n/a"
    return f"{quantize(value).quantize(Decimal('0.1'))}%"


def pts1(value: Decimal) -> str:
    return str(abs(value).quantize(Decimal("0.1")))


def _plural(n: int, singular: str, plural: str | None = None) -> str:
    return f"{n} {singular if n == 1 else (plural or singular + 's')}"


def _excerpt(text: str, limit: int = 160) -> str:
    clean = " ".join(text.split())
    return clean if len(clean) <= limit else clean[: limit - 3].rstrip() + "..."


def _mean(values: Sequence[Decimal]) -> Decimal | None:
    return quantize(sum(values, Decimal(0)) / len(values)) if values else None


def _diff(curr: Decimal | None, prev: Decimal | None) -> Decimal | None:
    return quantize(curr - prev) if curr is not None and prev is not None else None


def _subject_cell(entry: SubjectResult | None) -> CellValue:
    if entry is None:
        return None
    if entry.is_absent:
        return "AB"
    if entry.is_missing:
        return "-"
    return entry.marks


def _result_status(result: StudentResult) -> str:
    if not result.appeared:
        return "Absent"
    return "Pass" if result.passed else "Fail"


